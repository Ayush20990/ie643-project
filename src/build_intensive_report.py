"""Populate the supplied LaTeX template; never overwrite the historical report."""
import hashlib
import json
from pathlib import Path

from .config import ROOT


def main():
    folder=ROOT/'report'/'intensive';folder.mkdir(parents=True,exist_ok=True)
    template=ROOT/'report'/'official_template'/'IE643_Project_Report.tex'
    preamble=template.read_text(encoding='utf-8').split(r'\begin{document}')[0]
    # The supplied fourth macro argument is unused and its sample call supplies three.
    preamble=preamble.replace(r'\newcommand{\lecture}[4]',r'\newcommand{\lecture}[3]')
    # Restore actual bibliography citations instead of the teaching-template stub.
    preamble=preamble.replace(r'\renewcommand{\cite}[1]{[#1]}','% Teaching citation stub removed; natbib supplies actual citations.')
    extra=r'''
\usepackage{booktabs,longtable,array,placeins}
\usepackage[T1]{fontenc}
\usepackage{lmodern}
\setlength{\emergencystretch}{2em}
\hypersetup{colorlinks=true,linkcolor=blue,citecolor=blue,urlcolor=blue,pdftitle={DeepGen - IE643 Intensive Assessment Report},pdfauthor={Ayush Patel; Rishik Yadav}}
\newcommand{\evidencefigure}[3]{\begin{figure}[htbp]\centering\includegraphics[width=#3\linewidth]{../../results/forecast_horizons/figures/#1}\caption{#2}\end{figure}}
'''
    body=(folder/'report_body.tex').read_text(encoding='utf-8')
    path=folder/'IE643_Intensive_Assessment_Report.tex'
    path.write_text(preamble+extra+'\n'+body,encoding='utf-8')
    (folder/'template_provenance.json').write_text(json.dumps({
        'source':str(template.relative_to(ROOT)),'source_sha256':hashlib.sha256(template.read_bytes()).hexdigest(),
        'preserved':'article class, two-sided layout, page margins, header frame and section structure',
        'changes':['unused fourth header-macro argument removed to match sample call','real natbib citations replace teaching citation stub','packages for long tables, font encoding and float boundaries added'],
        'numerical_tables':'generated by src.build_submission_assets from preserved experiment CSVs',
        'team_allocation_source':'user supplied 20 October 2026','original_report_preserved':True},indent=2),encoding='utf-8')
    print(path)


if __name__=='__main__':main()
